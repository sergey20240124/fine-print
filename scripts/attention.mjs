/**
 * Вторая ось: заброшенность.
 *
 * Механическая разрешимость правил и неверная цена — независимые величины.
 * Первый прогон это показал наглядно: все три прошедших рынка оказались
 * сентябрьским заседанием ФРС с оборотами 18-30 млн долларов. Правила там
 * действительно исполнимы машиной, но исходный тезис был не «правила ясны»,
 * а «правила ясны, и их никто не прочитал». На решении ФРС непрочитанных
 * документов не бывает.
 *
 * Прямой измеритель внимания в данных есть — оборот. Тридцать миллионов
 * означают, что контракт разобран; двадцать тысяч — что на него не смотрели.
 *
 * Здесь эта величина считается не для витрины, а как ПРИОРИТЕТ для стадии C.
 * Стадия C стоит денег, пул большой, и порядок обхода решает, за что платим.
 *
 * Честная оговорка: это эвристика, а не измерение. Низкий оборот означает
 * «мало внимания», но с тем же успехом «никому не нужно» или «невозможно
 * исполнить». Поэтому заброшенность умножается на исполнимость, а не
 * заменяет её.
 */

/* Ниже этой ликвидности позиция неисполнима в любом разумном размере. */
const LIQ_FLOOR = 5_000;

/* Оборот, ниже которого рынок скорее мёртв, чем незамечен. */
const VOL_FLOOR = 20_000;

/* Верх шкалы: при таком обороте контракт разобран заведомо. */
const VOL_CEIL = 50_000_000;

export function attention(m) {
  const vol = Math.max(Number(m.vol) || 0, 1);
  const liq = Number(m.liq);
  const spread = m.spread == null ? null : Number(m.spread);

  /* Заброшенность линейна по логарифму оборота: 20 тыс. → 1, 50 млн → 0.
     Логарифм потому, что разница между 20 и 200 тысячами содержательна, а
     между 20 и 30 миллионами — нет, разобраны оба. */
  const lo = Math.log10(VOL_FLOOR), hi = Math.log10(VOL_CEIL);
  const neglect = vol < VOL_FLOOR ? 0.15
    : Math.min(1, Math.max(0, 1 - (Math.log10(vol) - lo) / (hi - lo)));

  /* Исполнимость: без ликвидности заброшенность ничего не стоит. */
  const tradeable = !isFinite(liq) ? 0.5
    : liq >= LIQ_FLOOR ? 1
    : Math.max(0.05, liq / LIQ_FLOOR);

  /* Спред штрафует мягко и только когда действительно широк.
     Первая версия наказывала линейно до нуля с пяти центов — и обнуляла
     весь сигнал, потому что у заброшенного рынка спред широк ПО ОПРЕДЕЛЕНИЮ.
     Штраф, съедающий ровно то, что ищешь, — не фильтр, а самообман. */
  const spreadOk = spread == null ? 0.9
    : spread <= 0.02 ? 1
    : Math.max(0.2, 1 - (spread - 0.02) / 0.08);

  const score = neglect * tradeable * spreadOk;

  return {
    score: +score.toFixed(4),
    neglect: +neglect.toFixed(3),
    tradeable: +tradeable.toFixed(3),
    spread_ok: +spreadOk.toFixed(3),
    why: vol < VOL_FLOOR ? 'оборот ниже порога: скорее мёртв, чем незамечен'
       : vol >= 10_000_000 ? 'рынок разобран, эдж от чтения правил маловероятен'
       : vol >= 1_000_000 ? 'умеренное внимание'
       : 'мало внимания — здесь чтение правил может что-то дать',
  };
}

/* Порядок обхода для платной стадии: сначала заброшенные и исполнимые. */
export function byAttention(a, b) {
  return attention(b).score - attention(a).score;
}
